-- Alert emails as one summary per check run instead of one email per signal. An account that switches
-- the summary on has its signal, lifecycle and outlook-change emails held here, encrypted like the
-- outbox, until its checks go quiet; the summary then goes through the outbox in the same transaction
-- that deletes the held items, so a signal is neither lost nor mailed twice.
alter table users add column alert_email_digest boolean not null default false;

create table email_digest_items (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users(id) on delete cascade,
    deduplication_key text not null unique,
    alert_event_id bigint references alert_events(id) on delete cascade,
    outlook_notification_id bigint references technical_outlook_notifications(id) on delete cascade,
    receipt varchar(16) not null,
    ciphertext text not null,
    iv text not null,
    created_at timestamptz not null default current_timestamp
);
create index email_digest_items_user on email_digest_items(user_id, id);

-- A delivered summary records the receipts of every email it carried.
alter table email_outbox add column digest_receipts text;
